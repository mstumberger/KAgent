#[cfg(test)]
mod tests;

use std::path::{Path, PathBuf};
use std::sync::RwLock;

use crate::config::{mask_key, ApiType, BuiltinCatalog, ModelConfigPatch, ModelEntry, ProviderEntry, ProvidersFile, Template};
use crate::discovery::correct_roles;
use crate::rules::{resolve, ModelConfig};

pub use patch::{ModelAdd, ModelChange, ProviderPatch, Refused};

/// `providers.json` version 2 (S40): the roles of the rows of an old fetch are corrected.
pub const SCHEMA_VERSION: u32 = 2;

pub struct ProviderStore {
    path: PathBuf,
    file: RwLock<ProvidersFile>,
    catalog: BuiltinCatalog,
    secrets: RwLock<Option<std::sync::Arc<dyn SecretSink>>>,
}

/// A model reference `"<providerId>::<modelId>"` split into its parts.
pub fn split_ref(model_ref: &str) -> Option<(&str, &str)> {
    let (p, m) = model_ref.split_once("::")?;
    if p.is_empty() || m.is_empty() {
        return None;
    }
    Some((p, m))
}

pub const SECRET_SERVICE: &str = "secret-service";

/// The models the settings name: `(setting, model ref)` for `chatModel`, `fastModel`,
/// `fallbackModel`, `visionModel` and `liveModel`.
pub type Named<'a> = [(&'a str, &'a str)];

/// Where API keys go when a keyring is available. Implementations must not block
/// (the daemon forwards to an async task).
pub trait SecretSink: Send + Sync {
    fn put(&self, provider_id: &str, key: &str);
    fn delete(&self, provider_id: &str);
}

pub struct ResolvedModel {
    pub provider: ProviderEntry,
    pub model: ModelEntry,
    pub config: ModelConfig,
}

impl ResolvedModel {
    /// A live (speech-to-speech) model by nature: it cannot answer text turns. The one
    /// place that decides it: the resolved config says so, every role the rules give is
    /// `live`, or the id reads as one (`discovery::roles_from_id`). The row's own roles
    /// are the owner's choice of job, checked apart (`ProviderStore::usable`).
    pub fn is_live(&self) -> bool {
        let rules_live = !self.config.roles.is_empty() && self.config.roles.iter().all(|x| x == "live");
        self.config.supports_live || rules_live || crate::discovery::roles_from_id(&self.model.id) == ["live"]
    }
}

impl ProviderStore {
    /// `named`: the models the settings name. They keep their roles when the rows of
    /// an old fetch are corrected (models.md section 3).
    pub fn load(path: impl Into<PathBuf>, catalog: BuiltinCatalog, named: &[String]) -> anyhow::Result<Self> {
        let path = path.into();
        let mut file = if path.exists() {
            serde_json::from_slice(&std::fs::read(&path)?)?
        } else {
            ProvidersFile { schema_version: SCHEMA_VERSION, ..Default::default() }
        };
        // Once, for a file written before S40: rows its fetch marked `chat` (a
        // text-to-speech, image or music model) get the roles of their id. In memory:
        // the next save writes them with the new version, so a role the owner gives
        // such a row later is never taken back at a start.
        if file.schema_version < SCHEMA_VERSION {
            for p in file.providers.values_mut() {
                let fixed = correct_roles(p, named);
                if fixed > 0 {
                    tracing::info!("{}: {} models are not chat models", p.id, fixed);
                }
            }
            file.schema_version = SCHEMA_VERSION;
        }
        Ok(Self { path, file: RwLock::new(file), catalog, secrets: RwLock::new(None) })
    }

    /// Convenience: builtin catalog parsed from the file generated by
    /// scripts/import-zcode-providers.py (embedded at build time).
    pub fn builtin_catalog() -> anyhow::Result<BuiltinCatalog> {
        Ok(serde_json::from_str(include_str!("../../../config/providers.builtin.json"))?)
    }

    pub fn templates(&self) -> &[Template] {
        &self.catalog.templates
    }

    /// Route API keys to a keyring from now on (see `SecretSink`). Existing plain keys
    /// migrate on the next `save()`.
    pub fn set_secret_sink(&self, sink: std::sync::Arc<dyn SecretSink>) {
        *self.secrets.write().unwrap() = Some(sink);
    }

    /// Put a key loaded from the keyring back into memory (no save).
    pub fn restore_key(&self, id: &str, key: String) {
        if let Some(p) = self.file.write().unwrap().providers.get_mut(id) {
            p.api_key = key;
        }
    }

    pub fn save(&self) -> anyhow::Result<()> {
        let sink = self.secrets.read().unwrap().clone();
        let (bytes, path) = {
            let mut file = self.file.write().unwrap();
            let mut on_disk = file.clone();
            if let Some(sink) = &sink {
                for (id, p) in file.providers.iter_mut() {
                    if p.api_key.is_empty() && p.api_key_ref.is_none() {
                        continue;
                    }
                    p.api_key_ref = Some(SECRET_SERVICE.into());
                    if p.api_key.is_empty() {
                        sink.delete(id);
                    } else {
                        sink.put(id, &p.api_key);
                    }
                }
                for (id, p) in on_disk.providers.iter_mut() {
                    p.api_key_ref = file.providers[id].api_key_ref.clone();
                }
            }
            for p in on_disk.providers.values_mut() {
                if p.api_key_ref.as_deref() == Some(SECRET_SERVICE) {
                    p.api_key.clear();
                }
            }
            (serde_json::to_vec_pretty(&on_disk)?, self.path.clone())
        };
        write_atomic_0600(&path, &bytes)
    }

    pub fn providers(&self) -> ProvidersFile {
        self.file.read().unwrap().clone()
    }

    pub fn provider(&self, id: &str) -> Option<ProviderEntry> {
        self.file.read().unwrap().providers.get(id).cloned()
    }

    pub fn update(&self, id: &str, f: impl FnOnce(&mut ProviderEntry)) -> anyhow::Result<ProviderEntry> {
        let (before, out) = {
            let mut file = self.file.write().unwrap();
            let entry = file.providers.get_mut(id).ok_or_else(|| anyhow::anyhow!("unknown provider {id}"))?;
            let before = entry.clone();
            f(entry);
            entry.last_error.clear();
            (before, entry.clone())
        };
        self.save_or_undo(id, before, &out)?;
        Ok(out)
    }

    /// The keys of `PUT /api/providers/:id` (models.md section 4). Every check runs
    /// before anything is written: a refused patch leaves the file as it was, and so
    /// does one whose save fails (memory included).
    pub fn patch(&self, id: &str, patch: &ProviderPatch, named: &Named<'_>) -> Result<ProviderEntry, Refused> {
        let (before, out) = {
            let mut file = self.file.write().unwrap();
            let entry = file.providers.get_mut(id).ok_or(Refused::UnknownProvider)?;
            let next = patch::plan(&self.catalog, entry, patch, named)?;
            let before = std::mem::replace(entry, next);
            entry.last_error.clear();
            (before, entry.clone())
        };
        self.save_or_undo(id, before, &out).map_err(|e| Refused::NotSaved(format!("{e:#}")))?;
        Ok(out)
    }

    /// Save; when the file cannot be written, put the entry back as it was, so memory
    /// never holds what the API reported as not saved. A change made by someone else in
    /// the meantime (the entry is no longer `after`) is left alone.
    fn save_or_undo(&self, id: &str, before: ProviderEntry, after: &ProviderEntry) -> anyhow::Result<()> {
        let result = self.save();
        if result.is_err() {
            let mut file = self.file.write().unwrap();
            if let Some(entry) = file.providers.get_mut(id) {
                // `save` may have set the key's reference: compare without it.
                let unchanged = ProviderEntry { api_key_ref: after.api_key_ref.clone(), ..entry.clone() } == *after;
                if unchanged {
                    *entry = before;
                }
            }
        }
        result
    }

    pub fn set_error(&self, id: &str, error: &str) {
        if let Some(p) = self.file.write().unwrap().providers.get_mut(id) {
            p.last_error = error.to_string();
        }
    }

    /// Add a provider from a template; ids are `templateId`, `templateId-2`, ... The
    /// `custom` template has no address of its own: `name` and `base_url` are required,
    /// and `api_type` chooses the message format (models.md section 4).
    #[allow(clippy::too_many_arguments)]
    pub fn add_from_template(
        &self,
        template_id: &str,
        name: Option<String>,
        base_url: Option<String>,
        api_key: Option<String>,
        headers: std::collections::BTreeMap<String, String>,
        api_type: Option<ApiType>,
    ) -> anyhow::Result<ProviderEntry> {
        let tpl = self
            .catalog
            .templates
            .iter()
            .find(|t| t.id == template_id)
            .ok_or_else(|| anyhow::anyhow!("unknown template {template_id}"))?;
        if tpl.id == "custom" {
            if name.as_deref().is_none_or(|n| n.trim().is_empty()) {
                anyhow::bail!("a custom provider needs a name");
            }
            if base_url.as_deref().is_none_or(|b| b.trim().is_empty()) {
                anyhow::bail!("a custom provider needs a base URL");
            }
        }
        if let Some(b) = base_url.as_deref().filter(|b| !b.trim().is_empty()) {
            patch::check_base_url(b).map_err(|e| anyhow::anyhow!(e))?;
        }
        let mut file = self.file.write().unwrap();
        let mut id = tpl.id.clone();
        let mut n = 2;
        while file.providers.contains_key(&id) {
            id = format!("{}-{n}", tpl.id);
            n += 1;
        }
        let mut api = tpl.api.clone();
        if let Some(base) = base_url.filter(|b| !b.is_empty()) {
            api.base_url = base;
        }
        if let Some(t) = api_type {
            api.api_type = t;
        }
        api.headers = headers;
        let models = tpl
            .models
            .iter()
            .chain(tpl.live_models.iter())
            .map(|m| ModelEntry {
                id: m.clone(),
                name: String::new(),
                // Live models are always on: they only show up in the voice picker.
                enabled: tpl.live_models.contains(m) || tpl.models.len() + tpl.live_models.len() < 5,
                roles: if tpl.live_models.contains(m) { vec!["live".into()] } else { vec!["chat".into()] },
                smart: true,
                config: ModelConfigPatch::default(),
            })
            .collect();
        let entry = ProviderEntry {
            id: id.clone(),
            name: name.unwrap_or_else(|| tpl.name.clone()),
            template_id: tpl.id.clone(),
            enabled: true,
            api,
            api_key: api_key.unwrap_or_default(),
            api_key_ref: None,
            models,
            models_fetched_at: None,
            last_error: String::new(),
        };
        file.order.push(id.clone());
        file.providers.insert(id, entry.clone());
        drop(file);
        self.save()?;
        Ok(entry)
    }

    /// Delete a provider; if it held the chat model the caller clears the setting.
    pub fn delete(&self, id: &str) -> anyhow::Result<()> {
        let mut file = self.file.write().unwrap();
        file.order.retain(|o| o != id);
        let removed = file.providers.remove(id).ok_or_else(|| anyhow::anyhow!("unknown provider {id}"))?;
        drop(file);
        // The keyring entry would otherwise outlive the provider.
        if removed.api_key_ref.as_deref() == Some(SECRET_SERVICE) {
            if let Some(sink) = self.secrets.read().unwrap().as_ref() {
                sink.delete(id);
            }
        }
        self.save()
    }

    pub fn set_order(&self, order: Vec<String>) -> anyhow::Result<()> {
        let mut file = self.file.write().unwrap();
        if order.iter().any(|o| !file.providers.contains_key(o)) {
            anyhow::bail!("order references an unknown provider");
        }
        let mut all: Vec<String> = file.order.clone();
        for id in &order {
            all.retain(|o| o != id);
        }
        file.order = order.into_iter().chain(all).collect();
        drop(file);
        self.save()
    }

    /// The config a model works with: `inherited` is what the built-in rules give it
    /// (an empty personal patch, smart on), `effective` what is sent (models.md
    /// section 2).
    pub fn configs(&self, provider: &ProviderEntry, model: &ModelEntry) -> (ModelConfig, ModelConfig) {
        let at = |personal: &ModelConfigPatch, smart| {
            resolve(&self.catalog, &model.id, provider.api.api_type.as_str(), &provider.api.base_url, &provider.template_id, personal, smart)
        };
        (at(&ModelConfigPatch::default(), true), at(&model.config, model.smart))
    }

    /// Resolve `"<providerId>::<modelId>"` into provider + model + full config.
    pub fn resolve(&self, model_ref: &str) -> anyhow::Result<ResolvedModel> {
        let (pid, mid) = split_ref(model_ref).ok_or_else(|| {
            anyhow::anyhow!("model reference must be <providerId>::<modelId>, got '{model_ref}'")
        })?;
        let file = self.file.read().unwrap();
        let provider = file
            .providers
            .get(pid)
            .ok_or_else(|| anyhow::anyhow!("unknown provider '{pid}' in '{model_ref}'"))?;
        let model = provider
            .models
            .iter()
            .find(|m| m.id == mid)
            .ok_or_else(|| anyhow::anyhow!("provider '{pid}' has no model '{mid}'"))?;
        let config = self.configs(provider, model).1;
        Ok(ResolvedModel { provider: provider.clone(), model: model.clone(), config })
    }

    /// The model a text turn may use: it exists, is enabled, has role `chat`, and its
    /// provider is enabled (models.md section 2). `None` for anything else.
    pub fn usable(&self, model_ref: &str) -> Option<ResolvedModel> {
        let r = self.resolve(model_ref).ok()?;
        (r.provider.enabled && r.model.enabled && r.model.roles.iter().any(|role| role == "chat")).then_some(r)
    }

    /// All enabled models of enabled providers with their resolved config, in `order` order.
    pub fn enabled_models(&self) -> Vec<(String, ModelEntry, ModelConfig)> {
        let file = self.file.read().unwrap();
        let mut out = Vec::new();
        for pid in &file.order {
            let Some(p) = file.providers.get(pid) else { continue };
            if !p.enabled {
                continue;
            }
            for m in &p.models {
                if !m.enabled {
                    continue;
                }
                out.push((pid.clone(), m.clone(), self.configs(p, m).1));
            }
        }
        out
    }

    /// One provider as the API shows it: the key masked, and every model with its
    /// `inherited` and `effective` config (models.md section 4).
    pub fn view(&self, p: &ProviderEntry) -> serde_json::Value {
        let models: Vec<serde_json::Value> = p
            .models
            .iter()
            .map(|m| {
                let (inherited, effective) = self.configs(p, m);
                serde_json::json!({
                    "id": m.id,
                    "name": m.name,
                    "enabled": m.enabled,
                    "roles": m.roles,
                    "smart": m.smart,
                    "config": m.config,
                    "inherited": inherited,
                    "effective": effective,
                })
            })
            .collect();
        serde_json::json!({
            "id": p.id,
            "name": p.name,
            "templateId": p.template_id,
            "enabled": p.enabled,
            "api": p.api,
            "apiKeyMasked": mask_key(&p.api_key),
            "hasKey": !p.api_key.is_empty(),
            "models": models,
            "modelsFetchedAt": p.models_fetched_at,
            "lastError": p.last_error,
        })
    }

    /// Every provider as the API shows it, in `order`.
    pub fn masked(&self) -> Vec<serde_json::Value> {
        let file = self.file.read().unwrap();
        file.order.iter().filter_map(|id| file.providers.get(id)).map(|p| self.view(p)).collect()
    }
}

fn write_atomic_0600(path: &Path, data: &[u8]) -> anyhow::Result<()> {
    use std::io::Write;
    use std::os::unix::fs::PermissionsExt;
    let tmp = path.with_extension("tmp");
    let mut f = std::fs::File::create(&tmp)?;
    f.write_all(data)?;
    f.set_permissions(std::fs::Permissions::from_mode(0o600))?;
    f.sync_all()?;
    drop(f);
    std::fs::rename(&tmp, path)?;
    Ok(())
}
